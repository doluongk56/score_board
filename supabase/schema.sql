-- Public được xem; chỉ tài khoản đã đăng nhập mới được sửa dữ liệu.

create table if not exists public.players (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 60),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create unique index if not exists players_name_unique
  on public.players (lower(trim(name)));

create table if not exists public.tours (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 100),
  game_key text not null default 'ta_la' constraint tours_game_key_length check (char_length(trim(game_key)) between 1 and 60),
  played_on date not null default current_date,
  created_at timestamptz not null default now()
);

alter table if exists public.tours
  add column if not exists game_key text not null default 'ta_la';

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'tours_game_key_length'
      and conrelid = 'public.tours'::regclass
  ) then
    alter table public.tours
      add constraint tours_game_key_length check (char_length(trim(game_key)) between 1 and 60);
  end if;
end;
$$;

create table if not exists public.tour_players (
  tour_id bigint not null references public.tours(id) on delete cascade,
  player_id bigint not null references public.players(id) on delete restrict,
  primary key (tour_id, player_id)
);

create table if not exists public.games (
  id bigint generated by default as identity primary key,
  tour_id bigint not null references public.tours(id) on delete cascade,
  game_number integer not null check (game_number > 0),
  created_at timestamptz not null default now(),
  unique (tour_id, game_number)
);

create table if not exists public.game_scores (
  game_id bigint not null references public.games(id) on delete cascade,
  player_id bigint not null references public.players(id) on delete restrict,
  score integer not null,
  primary key (game_id, player_id)
);

create index if not exists games_tour_id_idx on public.games(tour_id);
create index if not exists game_scores_player_id_idx on public.game_scores(player_id);

alter table public.players enable row level security;
alter table public.tours enable row level security;
alter table public.tour_players enable row level security;
alter table public.games enable row level security;
alter table public.game_scores enable row level security;

